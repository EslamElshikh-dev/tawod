const topicsBySlug = new Map(blogTopics.map((topic) => [topic.slug, topic]));
export const legacyTopicHubSlugs = new Set(blogTopics.map((topic) => topic.url?.match(/^\/blog\/([^/]+)\/$/)?.[1]).filter(Boolean));

export function topicForArticle(slug) {
  if (/turnkey/.test(slug)) return topicsBySlug.get("turnkey");
  if (/bone/.test(slug)) return topicsBySlug.get("bone-construction");
  if (/(saudi-code|saudi-building-code)/.test(slug)) return topicsBySlug.get("saudi-building-code");
  if (/(robot|drone|digital-twin|bim|smart-construction|future-construction|modern-construction-technolog)/.test(slug)) return topicsBySlug.get("construction-technology");
  if (/(electrical|plumbing|mechanical|mep)/.test(slug)) return topicsBySlug.get("mep");
  if (/(finishing|interior-design|decor)/.test(slug)) return topicsBySlug.get("finishing-interior");
  if (/(renovation|restoration|facade)/.test(slug)) return topicsBySlug.get("renovation");
  return topicsBySlug.get("general-contracting");
}

export function topicForService(file) {
  const mapping = {
    "service-construction.html": "bone-construction",
    "service-turnkey.html": "turnkey",
    "service-restoration.html": "renovation",
    "service-finishing.html": "finishing-interior",
    "service-decor.html": "finishing-interior",
    "service-mep.html": "mep",
  };
  return topicsBySlug.get(mapping[file]);
}

export function topicUrl(topic) {
  return topic.url || `/blog/topics/${topic.slug}/`;
}

export function articleRole(slug, topic = topicForArticle(slug)) {
  return slug === topic.pillar ? "pillar" : "supporting";
}
