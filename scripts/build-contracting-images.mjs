import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

const files = [...fs.readFileSync('sitemap.xml', 'utf8').matchAll(/<loc>([^<]+)<\/loc>/g)]
  .map(m => new URL(m[1]).pathname).filter(p => !p.startsWith('/maintenance/'))
  .map(p => p === '/' ? 'index.html' : p.endsWith('/') ? `${p.slice(1)}index.html` : p.slice(1));
const originals = new Set(files.filter(f => fs.existsSync(f)).flatMap(file =>
  [...fs.readFileSync(file, 'utf8').matchAll(/<img\b[^>]*>/gi)]
    .filter(([tag]) => !/\bsrcset=/.test(tag))
    .map(([tag]) => tag.match(/\bsrc=["']([^"']+)["']/i)?.[1])
    .filter(Boolean).map(src => src.replace(/^\//, '').replace(/^(?:\.\.\/)+/, '').split('?')[0])));
const output = 'images/responsive';
fs.mkdirSync(output, { recursive: true });
const profiles = {}, generated = new Set();
let originalBytes = 0, smallBytes = 0;
for (const file of [...originals].sort()) {
  // Existing hero art direction, logos and hand-tuned source sets stay intact.
  if (!/^images\//.test(file) || /\/logo\/|\/hero-/.test(file) || !fs.existsSync(file) || fs.statSync(file).size < 80 * 1024) continue;
  const meta = await sharp(file).metadata();
  if (!meta.width || !meta.height || meta.width < 800 || meta.pages > 1) continue;
  const widths = [...new Set([480, 768, Math.min(1200, meta.width)])].filter(w => w <= meta.width).sort((a,b) => a-b);
  const rows = [];
  for (const width of widths) {
    const bytes = await sharp(file).resize({ width, withoutEnlargement: true }).webp({ quality: 78, effort: 5 }).toBuffer();
    const name = `${path.parse(file).name}-${width}-${createHash('sha256').update(bytes).digest('hex').slice(0,12)}.webp`;
    const target = path.join(output, name);
    if (!fs.existsSync(target)) fs.writeFileSync(target, bytes);
    generated.add(name);
    rows.push({ url: `/${target}`, width });
    if (width === 480) smallBytes += bytes.length;
  }
  profiles[file] = rows;
  originalBytes += fs.statSync(file).size;
}
for (const file of fs.readdirSync(output)) if (!generated.has(file)) fs.unlinkSync(path.join(output, file));
fs.writeFileSync('lib/contracting-image-assets.mjs', `// Generated by build-contracting-images.mjs. Original image URLs remain available.\nexport const responsiveImages=${JSON.stringify(profiles)};\n`);
console.log(`Prepared ${Object.keys(profiles).length} responsive image sets (${generated.size} variants); originals ${originalBytes} bytes, 480px variants ${smallBytes} bytes.`);
