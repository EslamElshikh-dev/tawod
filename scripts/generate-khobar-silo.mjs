function focusSection(config, page) {
  const cards = config.cards.map(([icon, title, text]) => `<div class="feature-card"><i class="fa-solid ${icon}"></i><h3>${title}</h3><p>${text}</p></div>`).join('');
  return `<!-- KHOBAR_LOCAL_FOCUS_START --><section class="section-padding ${page === 'home' ? '' : 'bg-light '}khobar-local-focus"><div class="container"><div class="section-title reveal-up"><span class="eyebrow">${config.eyebrow}</span><h2>${config.focusTitle}</h2><p>${config.focusIntro}</p></div><div class="feature-grid">${cards}</div></div></section><!-- KHOBAR_LOCAL_FOCUS_END -->`;
}

function updatePageMetadata(html, sourceHtml, config) {
  const oldTitle = localizeString(sourceHtml.match(/<title>([\s\S]*?)<\/title>/i)?.[1] || '');
  const oldDescription = localizeString(sourceHtml.match(/<meta name="description" content="([^"]*)"/i)?.[1] || '');
  html = replaceEverywhere(html, oldTitle, config.title);
  html = replaceEverywhere(html, oldDescription, config.description);
  html = html.replace(/<title>[\s\S]*?<\/title>/i, `<title>${config.title}</title>`);
  html = html.replace(/<meta name="description" content="[^"]*">/i, `<meta name="description" content="${config.description}">`);
  html = html.replace(/<meta property="og:title" content="[^"]*">/i, `<meta property="og:title" content="${config.title}">`);
  html = html.replace(/<meta property="og:description" content="[^"]*">/i, `<meta property="og:description" content="${config.description}">`);
  html = html.replace(/<meta name="twitter:title" content="[^"]*">/i, `<meta name="twitter:title" content="${config.title}">`);
  html = html.replace(/<meta name="twitter:description" content="[^"]*">/i, `<meta name="twitter:description" content="${config.description}">`);
  return html;
}

function addCustomArticleCopy(html, article) {
  html = html.replace(/(<div class="article-note">[\s\S]*?<\/div>)/i, `$1\n<p class="khobar-local-note">${article.localIntro}</p>`);
  article.sections.forEach((section, index) => {
    const id = index + 1;
    const boundary = id < article.sections.length ? `<h2 id="article-section-${id + 1}">` : '<div class="seo-inline-cta">';
    const pattern = new RegExp(`(<h2 id="article-section-${id}">[\\s\\S]*?)(?=${escapeRegExp(boundary)})`, 'i');
    html = html.replace(pattern, (block) => `${block}<p class="khobar-local-note">${section.localParagraph}</p>\n`);
  });
  return html;
}

function updateArticleMetrics(html) {
  const body = html.match(/<article class="article-content[^>]*>([\s\S]*?)<\/article>/i)?.[1] || '';
  const wordCount = plainText(body).split(/\s+/).filter(Boolean).length;
  const minutes = Math.max(5, Math.ceil(wordCount / 170));
  return html
    .replace(/"wordCount":\d+/, `"wordCount":${wordCount}`)
    .replace(/"timeRequired":"PT\d+M"/, `"timeRequired":"PT${minutes}M"`)
    .replace(/(<span data-reading-time><i class="fa-regular fa-clock"><\/i>)\s*\d+ دقائق قراءة(<\/span>)/, `$1 ${minutes} دقائق قراءة$2`);
}

function renderArticle(article) {
  const sourceFile = path.join(root, 'dammam', 'blog', article.base.slug, 'index.html');
  const source = fs.readFileSync(sourceFile, 'utf8');
  let html = localizeString(source)
    .replace(/2026-08-13/g, date)
    .replace(/13 أغسطس 2026/g, '14 أغسطس 2026')
    .replace(/project-commercial-residential-building-(?:dammam|khobar)\.webp/g, 'project-luxury-villa-turnkey-alqusur.webp');
  const fields = ['title', 'seoTitle', 'description', 'ogDescription', 'heroIntro', 'conclusion', 'imageAlt'];
  for (const field of fields) html = replaceEverywhere(html, article.localized[field], article[field]);
  html = html.replace(/<title>[\s\S]*?<\/title>/i, `<title>${article.seoTitle}</title>`);
  html = html.replace(/<meta name="description" content="[^"]*">/i, `<meta name="description" content="${article.description}">`);
  html = html.replace(/<meta property="og:title" content="[^"]*">/i, `<meta property="og:title" content="${article.title}">`);
  html = html.replace(/<meta property="og:description" content="[^"]*">/i, `<meta property="og:description" content="${article.ogDescription}">`);
  html = html.replace(/<meta name="twitter:title" content="[^"]*">/i, `<meta name="twitter:title" content="${article.title}">`);
  html = html.replace(/<meta name="twitter:description" content="[^"]*">/i, `<meta name="twitter:description" content="${article.ogDescription}">`);
  html = addCustomArticleCopy(html, article);
  return updateArticleMetrics(html);
}

