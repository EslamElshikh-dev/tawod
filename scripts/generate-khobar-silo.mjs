function writeIfChanged(file, content) {
  const normalized = content.replace(/[ \t]+$/gm, '').replace(/\n{3,}/g, '\n\n').trim() + '\n';
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (old === normalized) return;
  changes.push(path.relative(root, file).split(path.sep).join('/'));
  if (!check) {
    fs.mkdirSync(path.dirname(file), {recursive: true});
    fs.writeFileSync(file, normalized);
  }
}

function localizeString(value) {
  return String(value)
    .replace(/DAMMAM/g, 'KHOBAR')
    .replace(/Dammam/g, 'Khobar')
    .replace(/dammam/g, 'khobar')
    .replace(/الدمام/g, 'الخبر');
}

function localizeObject(value) {
  if (Array.isArray(value)) return value.map(localizeObject);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, localizeObject(item)]));
  return typeof value === 'string' ? localizeString(value) : value;
}

function replaceEverywhere(html, from, to) {
  return from && from !== to ? html.replace(new RegExp(escapeRegExp(from), 'g'), () => to) : html;
}

