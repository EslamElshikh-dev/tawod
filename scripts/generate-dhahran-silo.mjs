const articleSources = new Map();
for (const [sourceSlug, config] of Object.entries(articleConfigs)) {
  const sourceFile = path.join(root, 'khobar', 'blog', sourceSlug, 'index.html');
  const html = fs.readFileSync(sourceFile, 'utf8');
  articleSources.set(sourceSlug, {
    ...config,
    sourceSlug,
    slug: sourceSlug.replace(/-khobar$/, '-dhahran'),
    sourceHtml: html,
    oldTitle: localize(extract(html, /<h1>([\s\S]*?)<\/h1>/i)),
    oldSeoTitle: localize(extract(html, /<title>([\s\S]*?)<\/title>/i)),
    oldDescription: localize(extract(html, /<meta name="description" content="([^"]*)"/i)),
    oldOgDescription: localize(extract(html, /<meta property="og:description" content="([^"]*)"/i)),
    oldHeroIntro: localize(extract(html, /<section class="article-hero"[\s\S]*?<\/h1><p>([\s\S]*?)<\/p>/i)),
    oldConclusion: localize(extract(html, /<h2 id="article-conclusion">[\s\S]*?<\/h2>\s*<p>([\s\S]*?)<\/p>/i)),
    oldImageAlt: localize(extract(html, /<meta property="og:image:alt" content="([^"]*)"/i))
  });
}

const articles = [...articleSources.values()];

function applyArticleContent(html) {
  for (const article of articles) {
    html = replaceEverywhere(html, article.oldTitle, article.title);
    html = replaceEverywhere(html, article.oldSeoTitle, article.seoTitle);
    html = replaceEverywhere(html, article.oldDescription, article.description);
    html = replaceEverywhere(html, article.oldOgDescription, article.ogDescription);
    html = replaceEverywhere(html, article.oldImageAlt, article.imageAlt || article.oldImageAlt);
  }
  return html;
}

function updateArticleMetrics(html) {
  const body = extract(html, /<article class="article-content[^>]*>([\s\S]*?)<\/article>/i);
  const wordCount = plainText(body).split(/\s+/).filter(Boolean).length;
  const minutes = Math.max(5, Math.ceil(wordCount / 170));
  return html
    .replace(/"wordCount":\d+/, `"wordCount":${wordCount}`)
    .replace(/"timeRequired":"PT\d+M"/, `"timeRequired":"PT${minutes}M"`)
    .replace(/(<span data-reading-time><i class="fa-regular fa-clock"><\/i>)\s*\d+ دقائق قراءة(<\/span>)/, `$1 ${minutes} دقائق قراءة$2`);
}

function renderArticle(article) {
  let html = applyArticleContent(localize(article.sourceHtml));
  html = replaceEverywhere(html, article.oldHeroIntro, article.heroIntro);
  html = replaceEverywhere(html, article.oldConclusion, article.conclusion);
  let noteIndex = 0;
  html = html.replace(/<p class="dhahran-local-note">[\s\S]*?<\/p>/gi, () => `<p class="dhahran-local-note">${article.notes[noteIndex++]}</p>`);
  if (noteIndex !== article.notes.length) throw new Error(`${article.sourceSlug}: expected ${article.notes.length} local notes, replaced ${noteIndex}`);
  html = html.replace(/<title>[\s\S]*?<\/title>/i, `<title>${article.seoTitle}</title>`)
    .replace(/<meta name="description" content="[^"]*">/i, `<meta name="description" content="${article.description}">`)
    .replace(/<meta property="og:title" content="[^"]*">/i, `<meta property="og:title" content="${article.title}">`)
    .replace(/<meta property="og:description" content="[^"]*">/i, `<meta property="og:description" content="${article.ogDescription}">`)
    .replace(/<meta name="twitter:title" content="[^"]*">/i, `<meta name="twitter:title" content="${article.title}">`)
    .replace(/<meta name="twitter:description" content="[^"]*">/i, `<meta name="twitter:description" content="${article.ogDescription}">`);
  return updateArticleMetrics(html);
}

function focusSection(config, page) {
  const cards = config.cards.map(([icon, title, body]) => `<div class="feature-card"><i class="fa-solid ${icon}"></i><h3>${title}</h3><p>${body}</p></div>`).join('');
  return `<!-- DHAHRAN_LOCAL_FOCUS_START --><section class="section-padding ${page === 'home' ? '' : 'bg-light '}dhahran-local-focus"><div class="container"><div class="section-title reveal-up"><span class="eyebrow">${config.eyebrow}</span><h2>${config.focusTitle}</h2><p>${config.focusIntro}</p></div><div class="feature-grid">${cards}</div></div></section><!-- DHAHRAN_LOCAL_FOCUS_END -->`;
}

function replaceFocus(html, config, page) {
  const block = focusSection(config, page);
  const marker = /<!-- DHAHRAN_LOCAL_FOCUS_START -->[\s\S]*?<!-- DHAHRAN_LOCAL_FOCUS_END -->/i;
  return marker.test(html) ? html.replace(marker, block) : html.replace(/<section id="faq"/i, `${block}\n<section id="faq"`);
}

function updatePageMetadata(html, source, config) {
  const oldTitle = localize(extract(source, /<title>([\s\S]*?)<\/title>/i));
  const oldDescription = localize(extract(source, /<meta name="description" content="([^"]*)"/i));
  html = replaceEverywhere(html, oldTitle, config.title);
  html = replaceEverywhere(html, oldDescription, config.description);
  return html.replace(/<title>[\s\S]*?<\/title>/i, `<title>${config.title}</title>`)
    .replace(/<meta name="description" content="[^"]*">/i, `<meta name="description" content="${config.description}">`)
    .replace(/<meta property="og:title" content="[^"]*">/i, `<meta property="og:title" content="${config.title}">`)
    .replace(/<meta property="og:description" content="[^"]*">/i, `<meta property="og:description" content="${config.description}">`)
    .replace(/<meta name="twitter:title" content="[^"]*">/i, `<meta name="twitter:title" content="${config.title}">`)
    .replace(/<meta name="twitter:description" content="[^"]*">/i, `<meta name="twitter:description" content="${config.description}">`);
}

function renderPage(page) {
  const sourceFile = page === 'home' ? path.join(root, 'khobar', 'index.html') : path.join(root, 'khobar', page, 'index.html');
  const source = fs.readFileSync(sourceFile, 'utf8');
  const config = pageConfigs[page];
  let html = updatePageMetadata(applyArticleContent(localize(source)), source, config);
  if (page === 'home') {
    html = html.replace(/<h1 id="dhahran-hero-title">[\s\S]*?<\/h1>/i, `<h1 id="dhahran-hero-title"><span class="hero-title-main">${config.h1}</span><span class="hero-title-sub">${config.sub}</span></h1>`)
      .replace(/(<section class="hero"[\s\S]*?<\/h1>)<p>[\s\S]*?<\/p>/i, `$1<p>${config.lead}</p>`);
  } else {
    html = html.replace(/(<section class="page-hero"[\s\S]*?)<h1>[\s\S]*?<\/h1><p>[\s\S]*?<\/p>/i, `$1<h1>${config.h1}</h1><p>${config.lead}</p>`);
  }
  return replaceFocus(html, config, page);
}

