function writeIfChanged(file, content) {
  const normalized = content.replace(/[ \t]+$/gm, '').replace(/\n{3,}/g, '\n\n').trim() + '\n';
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (old === normalized) return;
  changes.push(path.relative(root, file).split(path.sep).join('/'));
  if (!check) {
    fs.mkdirSync(path.dirname(file), {recursive: true});
    fs.writeFileSync(file, normalized);
  }
}

function localize(value) {
  return String(value)
    .replace(/KHOBAR/g, 'DHAHRAN')
    .replace(/Khobar/g, 'Dhahran')
    .replace(/khobar/g, 'dhahran')
    .replace(/الخبر(?!ة)/g, 'الظهران');
}

function replaceEverywhere(html, from, to) {
  return from && from !== to ? html.replace(new RegExp(escapeRegExp(from), 'g'), () => to) : html;
}

