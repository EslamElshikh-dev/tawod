import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative, sep } from "node:path";
import process from "node:process";

const root = process.cwd();
const output = join(root, "lib", "legacy-html-files.ts");
const check = process.argv.includes("--check");
const excludedDirectories = new Set([
  ".git",
  ".next",
  "app",
  "lib",
  "node_modules",
  "out",
  "project-pages",
  "public",
]);

function collectHtmlFiles(directory) {
  const files = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!excludedDirectories.has(entry.name)) files.push(...collectHtmlFiles(join(directory, entry.name)));
      continue;
    }
    if (entry.isFile() && entry.name.endsWith(".html")) {
      files.push(relative(root, join(directory, entry.name)).split(sep).join("/"));
    }
  }
  return files;
}

const files = collectHtmlFiles(root).sort((a, b) => a.localeCompare(b, "en"));
const hashes = Object.fromEntries(files.map((file) => [
  file,
  createHash("sha256").update(readFileSync(join(root, file))).digest("hex"),
]));
const source = `// Generated by scripts/generate-legacy-html-manifest.mjs.\n// Do not edit by hand; paths and content hashes invalidate the Next.js build cache.\nexport const legacyHtmlFiles = ${JSON.stringify(files, null, 2)} as const;\nexport const legacyHtmlHashes = ${JSON.stringify(hashes, null, 2)} as const;\n`;
const current = (() => {
  try { return readFileSync(output, "utf8"); }
  catch { return ""; }
})();

if (check && current !== source) {
  console.error("Legacy HTML route manifest is out of date. Run node scripts/generate-legacy-html-manifest.mjs");
  process.exit(1);
}
if (!check && current !== source) writeFileSync(output, source);
console.log(`${check ? "Checked" : "Generated"} legacy HTML manifest with ${files.length} routes${current === source ? "; unchanged" : ""}.`);
